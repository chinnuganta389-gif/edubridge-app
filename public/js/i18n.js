// Current active language: default 'en' or from localStorage
let currentLang = localStorage.getItem('edubridge_lang') || 'en';

function setLanguage(lang) {
  if (lang !== 'en' && lang !== 'te') lang = 'en';
  currentLang = lang;
  localStorage.setItem('edubridge_lang', lang);

  if (lang === 'te') {
    document.body.classList.add('lang-te');
  } else {
    document.body.classList.remove('lang-te');
  }

  updatePageTranslations();

  // If user is logged in, sync preference with backend
  if (window.EduAuth && window.EduAuth.currentUser) {
    window.EduAuth.updateProfile({ preferred_language: lang });
  }

  // Update language toggle button label
  const btn = document.getElementById('langToggleBtn');
  if (btn) {
    btn.innerHTML = lang === 'en' ? '🌐 తెలుగు (TE)' : '🌐 English (EN)';
  }

  // Trigger custom event for page-specific components to re-render
  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
}

function t(key) {
  const dict = EduTranslations[currentLang] || EduTranslations.en;
  return dict[key] || EduTranslations.en[key] || key;
}

function updatePageTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const translated = t(key);
    if (translated) {
      if (el.tagName === 'INPUT' && el.getAttribute('placeholder')) {
        el.setAttribute('placeholder', translated);
      } else {
        el.textContent = translated;
      }
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    const translated = t(key);
    if (translated) {
      el.setAttribute('placeholder', translated);
    }
  });
}

function toggleLanguage() {
  const nextLang = currentLang === 'en' ? 'te' : 'en';
  setLanguage(nextLang);
}

// Auto-run on DOM ready
document.addEventListener('DOMContentLoaded', () => {
  setLanguage(currentLang);
});
